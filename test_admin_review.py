class QrSvg(Base):
    """The QR field comes from a remote service: parse as XML, allow-list, re-emit; never pass markup through."""
    def test_real_supabase_format_is_accepted_and_cleaned(self):
        for raw in (REAL, "  \n" + REAL, "data:image/svg+xml;utf-8," + quote(REAL), "data:image/svg+xml;base64," + __import__("base64").b64encode(REAL.encode()).decode()):
            svg, why = ar._svg_parse(raw)
            self.assertIsNone(why, raw[:40])
            self.assertTrue(svg.startswith('<svg xmlns="http://www.w3.org/2000/svg" width="45"'))
            self.assertEqual(svg.count("<rect"), 2)
            for gone in ("<?xml", "<!--", "SVGo", "xlink", "\n"):
                self.assertNotIn(gone, svg)
            import xml.etree.ElementTree as ET
            ET.fromstring(svg)                                  # output is well-formed

    def test_prolog_variants(self):
        decl = '<?xml version="1.0" encoding="UTF-8" standalone="no"?>'
